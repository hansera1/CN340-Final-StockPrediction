def inline(s):
    s = html.escape(s.strip(), quote=False)
    s = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", s)
    return re.sub(r"`(.+?)`", r"<code>\1</code>", s)


def md_table(name, n=0, drop=()):
    """ตารางลำดับที่ n ในไฟล์ results/<name> → HTML · ตัดคอลัมน์ตามชื่อใน drop"""
    groups, cur = [], []
    for line in (RES / name).read_text(encoding="utf-8").splitlines():
        if line.startswith("|"):
            cur.append(line)
        elif cur:
            groups.append(cur)
            cur = []
    if cur:
        groups.append(cur)
    cells = [re.split(r"(?<!\\)\|", g.strip().strip("|")) for g in groups[n] if not re.fullmatch(r"[|\-\s:]+", g)]
    head, rows = cells[0], cells[1:]
    keep = [i for i, h in enumerate(head) if h.strip() not in drop]
    fix = lambda c: inline(c.replace("\\|", "|"))
    return table([fix(head[i]) for i in keep], [[fix(r[i]) for i in keep] for r in rows], "wide")


